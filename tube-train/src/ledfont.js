const CAP = 7;                        // rows from the top of a capital to the baseline

function glyph(ch) { return GLYPHS[ch] || GLYPHS['?']; }

// how many dots wide a line of text is
export function ledWidth(text, scale = 1) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1) * scale;
}

// Lays text out on a grid of cols × rows dots and returns which are lit, row
// by row. `text` can be several lines, each with its capitals centred in its
// share of the rows, and a tab in a line pushes what follows it to the
// right. `scale` draws each dot of the font as a square of dots.
export function ledBitmap(text, cols, rows, { align = 'center', scale = 1 } = {}) {
  const lit = new Uint8Array(cols * rows);
  const lines = [].concat(text);
  const put = (str, x0, top) => {
    let x = x0;
    for (const ch of str) {
      const g = glyph(ch);
      g.forEach((row, j) => {
        for (let i = 0; i < row.length; i++) {
          if (row[i] !== '#') continue;
          for (let a = 0; a < scale; a++) for (let b = 0; b < scale; b++) {
            const c = x + i * scale + a, r = top + j * scale + b;
            if (c >= 0 && c < cols && r >= 0 && r < rows) lit[r * cols + c] = 1;
          }
        }
      });
      x += (g[0].length + 1) * scale;
    }
  };
  lines.forEach((line, n) => {
    const top = Math.round(rows * (n + 0.5) / lines.length - CAP * scale / 2);
    const [left, right] = line.split('\t');
    const w = ledWidth(left, scale);
    if (right !== undefined) {
      put(left, 1, top);
      put(right, cols - 1 - ledWidth(right, scale), top);
    } else {
      put(left, align === 'left' ? 1 : align === 'right' ? cols - 1 - w : Math.floor((cols - w) / 2), top);
    }
  });
  return lit;
}
