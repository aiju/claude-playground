"""python3 -m emc report: regenerate docs/performance-v0.md.

Every program runs once on the ISA simulator, recording its trace; the
trace is then replayed through each pipeline preset. The cycle times come
from the static timing analysis of the netlist (emc/hw/sta.py).
"""

import math
import os
import time
from array import array

from . import asm, isa, pipeline, testing
from .sim import Machine

OUT = os.path.join(testing.ROOT, "docs", "performance-v0.md")
CAUSES = [("branch", "branches"), ("load", "loads, SLT"), ("muldiv", "mul/div"), ("bus", "bus"), ("alu", "other")]


def measure(names):
    rows = {}
    for name in names:
        path = testing.program_path(name)
        img = asm.assemble_file(isa, path)
        inp = testing.program_input(path)
        m = Machine(img, inp)
        trace = array("Q")
        stop = m.run(500_000_000, None, trace)
        if stop.cause != "halt":
            raise RuntimeError(f"{name}: {stop}")
        res = {}
        for cname, cfg in pipeline.PRESETS.items():
            t = pipeline.Timing(Machine(img, inp), cfg)
            t.replay(trace)
            res[cname] = t.report()
        rows[name] = (m.instructions, res)
    return rows


def clock_times():
    from .hw import cpu, sta
    out = []
    for label, kw in (("all 10H", {}), ("E151 registers", {"ff": sta.E151})):
        nl = cpu.build(**kw)
        out.append((label, sta.Timing(nl, cpu.EXTERNAL, **kw).analyse()["T"]))
    return out


def pct(a, b):
    return f"{100 * (a - b) / b:+.1f}%"


def render(rows, clocks):
    base = "p5"
    names = list(rows)
    L = []
    P = L.append
    P("# Performance of draft 0")
    P("")
    P("Generated by `python3 -m emc report`; don't edit by hand. The programs and")
    P("what they do are in [programs/](../programs), the pipeline presets in")
    P("[emc/pipeline.py](../emc/pipeline.py), and the hardware in")
    P("[hardware-v0.md](hardware-v0.md).")
    P("")
    P(f"`{base}` is {pipeline.PRESETS[base].desc}.")
    P("Its cycle counts are exact: the chip-level netlist runs every program in")
    P("the same number of cycles (`python3 -m emc hw run NAME`).")
    P("")
    P(f"## The hardware ({base})")
    P("")
    hdr = "| Program | Instructions | Cycles | CPI | " + " | ".join(
        f"ms at {1000 / T:.1f} MHz ({lbl})" for lbl, T in clocks) + " | Cycles lost to " + ", ".join(
        c for _, c in CAUSES) + " |"
    P(hdr)
    P("|---|" + "---:|" * (3 + len(clocks)) + "---|")
    tot_i = tot_c = 0
    for name in names:
        n, res = rows[name]
        r = res[base]
        tot_i += n
        tot_c += r["cycles"]
        lost = " / ".join(f"{100 * r['lost'].get(k, 0) / r['cycles']:.0f}%" for k, _ in CAUSES)
        times = " | ".join(f"{r['cycles'] * T / 1e6:.1f}" for _, T in clocks)
        P(f"| {name} | {n:,} | {r['cycles']:,} | {r['cpi']:.2f} | {times} | {lost} |")
    P("")
    P(f"Over all {len(names)} programs: {tot_i:,} instructions in {tot_c:,} cycles,")
    P(f"CPI {tot_c / tot_i:.2f}. Cycles lost are cycles in which no instruction")
    P("entered EX, by the reason the next one waited.")
    P("")
    P("## Pipeline variants")
    P("")
    P(f"Cycles against `{base}` (negative is faster). Clock-rate effects are not")
    P("included: a variant that lengthens the critical path costs that on top.")
    P("")
    others = [c for c in pipeline.PRESETS if c != base]
    P("| Program | " + " | ".join(f"`{c}`" for c in others) + " |")
    P("|---|" + "---:|" * len(others))
    logs = {c: 0.0 for c in others}
    for name in names:
        n, res = rows[name]
        b = res[base]["cycles"]
        cells = []
        for c in others:
            cells.append(pct(res[c]["cycles"], b))
            logs[c] += math.log(res[c]["cycles"] / b)
        P(f"| {name} | " + " | ".join(cells) + " |")
    P("| **geometric mean** | " + " | ".join(
        f"**{100 * (math.exp(logs[c] / len(names)) - 1):+.1f}%**" for c in others) + " |")
    P("")
    for c in others:
        P(f"- `{c}`: {pipeline.PRESETS[c].desc}.")
    P("")
    P("## Branches")
    P("")
    P("| Program | Conditional branches | Mispredicted | Rate |")
    P("|---|---:|---:|---:|")
    for name in names:
        r = rows[name][1][base]
        rate = 100 * r["mispredicts"] / r["branches"] if r["branches"] else 0
        P(f"| {name} | {r['branches']:,} | {r['mispredicts']:,} | {rate:.1f}% |")
    P("")
    return "\n".join(L)


def main(args=None):
    t0 = time.time()
    names = [n for n in testing.program_names() if n != "hello"]
    rows = measure(names)
    clocks = clock_times()
    text = render(rows, clocks)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT)} ({time.time() - t0:.0f} s)")
